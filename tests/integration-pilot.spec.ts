const hash = (b: Buffer) => createHash('sha256').update(b).digest('hex');
// Read only the bounded STORED archive generated by our exporter, not arbitrary client ZIPs.
function archive(bytes: Buffer) {
  const files = new Map<string, Buffer>(); let position = 0;
  while (bytes.readUInt32LE(position) === 0x04034b50) {
    expect(bytes.readUInt16LE(position + 8)).toBe(0);
    const size = bytes.readUInt32LE(position + 18), nameSize = bytes.readUInt16LE(position + 26), extra = bytes.readUInt16LE(position + 28);
    const name = bytes.subarray(position + 30, position + 30 + nameSize).toString(), begin = position + 30 + nameSize + extra;
    expect(files.has(name)).toBe(false); expect(begin + size).toBeLessThanOrEqual(bytes.length);
    files.set(name, bytes.subarray(begin, begin + size)); position = begin + size;
  }
  return files;
}
