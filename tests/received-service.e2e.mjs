import assert from 'node:assert/strict';
import http from 'node:http';
import { createRequire } from 'node:module';
import { randomUUID, createHash } from 'node:crypto';
import { receivedXml, receivedCdr } from './received-fixture.mjs';
if (!process.argv.includes('--isolated-synthetic-only') || process.env.DB_HOST !== 'received-postgres' || process.env.DB_NAME !== 'factuez_received_qa' || process.env.DATABASE_URL)
  throw new Error('Este ensayo requiere el runtime y la BD nueva de recepción QA');
const require = createRequire(new URL('../services/received-documents-service/package.json', import.meta.url));
require('reflect-metadata');
const { NestFactory } = require('@nestjs/core');
const { AppModule } = require('./dist/app.module.js');
const { ReceptionPrisma } = require('./dist/prisma.service.js');
const ExcelJS = require('exceljs');
const { AccessError } = require('@factuez/service-access');
const branch = randomUUID(), otherBranch = randomUUID(), userId = randomUUID();
const companyId = 900000101, otherCompanyId = 900000202;
const catalog = { companies: [{ id: companyId, ruc: '00000000101', legalName: 'QA RECEPTOR FICTICIO', environment: 'BETA' }, { id: otherCompanyId, ruc: '00000000202', legalName: 'QA OTRO RECEPTOR', environment: 'BETA' }], branches: [{ id: branch, companyId }, { id: otherBranch, companyId: otherCompanyId }] };
const stub = http.createServer((request, res) => {
  const token = request.headers.authorization;
  if (!['Bearer qa-admin', 'Bearer qa-assigned', 'Bearer qa-denied'].includes(token)) { res.writeHead(401).end(); return; }
  const permissions = token === 'Bearer qa-denied' ? [] : ['report.view', 'report.export', 'setup.manage', 'document.view'];
  const scope = token === 'Bearer qa-assigned' ? { kind: 'ASSIGNED', branchIds: [otherBranch], emissionPointIds: [], series: [] } : { kind: 'GLOBAL' };
  res.setHeader('Content-Type', 'application/json');
  res.end(JSON.stringify(request.url === '/api/v1/auth/me' ? { sub: userId, roles: token === 'Bearer qa-assigned' ? ['STATION_MANAGER'] : ['ADMIN'], permissions, scope, exp: Math.floor(Date.now() / 1000) + 300 } : catalog));
});
await new Promise(resolve => stub.listen(0, '127.0.0.1', resolve));
const stubUrl = `http://127.0.0.1:${stub.address().port}`;
process.env.IDENTITY_INTERNAL_URL = stubUrl; process.env.BILLING_INTERNAL_URL = stubUrl;
const app = await NestFactory.create(AppModule, { logger: false });
app.useBodyParser('json', { limit: '18mb' });
app.useGlobalFilters({ catch(error, host) { const status = error instanceof AccessError ? error.status : 500; host.switchToHttp().getResponse().status(status).json({ message: error instanceof AccessError ? error.message : 'Error QA' }); } });
await app.listen(0, '127.0.0.1');
const url = await app.getUrl(), db = app.get(ReceptionPrisma);
let checks = 0;
const call = (path, method = 'GET', body, token = 'qa-admin') => fetch(`${url}/api/v1/received-documents${path}`, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
const check = (actual, expected) => { assert.equal(actual, expected); checks++; };
try {
  const number = `FQA1-${String(Date.now() % 99999999).padStart(8, '0')}`;
  const xml = receivedXml('01', number), contentBase64 = Buffer.from(xml).toString('base64');
  const command = { companyId, branchId: branch, files: [{ fileName: 'invoice-ficticia.xml', contentBase64 }] };
  check((await call('', 'POST', command, 'qa-denied')).status, 403);
  check((await call('', 'POST', { ...command, companyId: otherCompanyId })).status, 403);
  const wrongRecipient = await call('', 'POST', { ...command, companyId: otherCompanyId, branchId: otherBranch });
  check(wrongRecipient.status, 201); check((await wrongRecipient.json()).results[0].outcome, 'REJECTED');
  const [first, second] = await Promise.all([call('', 'POST', command), call('', 'POST', command)]);
  check(first.status, 201); check(second.status, 201);
  const r1 = await first.json(), r2 = await second.json();
  check([r1.results[0].outcome, r2.results[0].outcome].sort().join(','), 'DUPLICATE,IMPORTED');
  const id = r1.results[0].id;
  const detailRes = await call(`/${id}`); check(detailRes.status, 200);
  const detail = await detailRes.json(); check(detail.projection.items[0].unitValue, '20.000000'); check(detail.itemCount, 1); check(detail.sunatStatus, 'NOT_CHECKED');
  check((await call(`/${id}`, 'GET', undefined, 'qa-assigned')).status, 404);
  check((await call(`/${id}/artifacts/${detail.artifacts[0].id}`, 'GET', undefined, 'qa-assigned')).status, 404);
  const original = await call(`/${id}/artifacts/${detail.artifacts[0].id}`);
  check(Buffer.from(await original.arrayBuffer()).equals(Buffer.from(xml)), true);
  check(original.headers.get('cache-control'), 'no-store');
  const conflict = await (await call('', 'POST', { ...command, files: [{ fileName: 'different.xml', contentBase64: Buffer.from(xml.replace('Combustible ficticio', 'Alterado ficticio')).toString('base64') }] })).json();
  check(conflict.results[0].outcome, 'REJECTED');
  const attach = { kind: 'CDR', fileName: 'R-ficticia.xml', contentBase64: Buffer.from(receivedCdr(number)).toString('base64') };
  check((await call(`/${id}/artifacts`, 'POST', attach)).status, 201);
  check((await (await call(`/${id}/artifacts`, 'POST', attach)).json()).duplicate, true);
  check((await call(`/${id}/artifacts`, 'POST', { ...attach, contentBase64: Buffer.from(receivedCdr('FQA1-99999999')).toString('base64') })).status, 400);
  check((await call(`/${id}/registration`, 'PATCH', { registered: true })).status, 400);
  check((await call(`/${id}/registration`, 'PATCH', { registered: true, erpReference: 'QA-ERP-1' })).status, 200);
  const updated = await (await call(`/${id}`)).json(); check(updated.erpReference, 'QA-ERP-1'); check(updated.sunatStatus, 'NOT_CHECKED');
  const pdf = await call(`/${id}/pdf`); check(pdf.status, 200); check(Buffer.from(await pdf.arrayBuffer()).subarray(0, 5).toString(), '%PDF-');
  const cacheHit = await call(`/${id}/pdf`, 'GET', undefined, 'qa-assigned'); check(cacheHit.status, 404);
  const list = await (await call(`?companyId=${companyId}&dataSource=SYNTHETIC&q=${number}`)).json(); check(list.total, 1);
  const other = await (await call(`?companyId=${otherCompanyId}&dataSource=SYNTHETIC&q=${number}`)).json(); check(other.total, 0);
  const empty = await (await call(`?companyId=${companyId}&dataSource=BUSINESS`)).json(); check(empty.total, 0);
  const excel = await call(`/export.xlsx?companyId=${companyId}&dataSource=SYNTHETIC&q=${number}`); check(excel.status, 200);
  const book = new ExcelJS.Workbook(); await book.xlsx.load(Buffer.from(await excel.arrayBuffer()));
  check(book.getWorksheet('Cabeceras').rowCount, 2); check(book.getWorksheet('Items').getCell('K2').value, '20.000000');
  check(await db.receivedDocument.count({ where: { companyId, fullNumber: number } }), 1);
  check(await db.receivedItemRecord.count({ where: { documentId: id } }), 1);
  check(await db.receivedAudit.count({ where: { documentId: id } }), 4);
  check(createHash('sha256').update(contentBase64, 'base64').digest('hex'), detail.projection.xmlSha256);
  console.log(JSON.stringify({ status: 'PASS', checks, syntheticOnly: true, officialRequests: 0, existingBillingWrites: 0 }));
} finally { await app.close(); await new Promise(resolve => stub.close(resolve)); }
