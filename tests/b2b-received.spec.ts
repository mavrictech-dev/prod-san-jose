import 'reflect-metadata';
import {beforeEach,describe,expect,it} from 'vitest';
import {B2bReceptionReads} from '../services/received-documents-service/src/b2b/read';
import {b2bReceivedFixture,receivedId,receivedHash} from './helpers/b2b-received.fixture';
import {receivedSubject} from '../packages/service-access/src/b2b-received-wire';
describe('B2B08 incoming-document read authority and original evidence',()=>{
  let f:ReturnType<typeof b2bReceivedFixture>;
  beforeEach(async()=>{f=b2bReceivedFixture();await f.grant('READ');await f.grant('ARTIFACT');});
  it('reads full original item/tax decimals without changing any incoming or issued state',async()=>{
    const v=await f.facade.detail(f.token,'SERVICE',f.scope,f.id);
    expect(v.projection.items[0]).toMatchObject({quantity:'5.000',unitValue:'20.000000',unitPrice:'23.60',lineExtensionAmount:'100.00'});
    expect(v.projection.items[0].taxes[0].amount).toBe('18.00');expect(v.fiscalAcceptance).toBe('NOT_VERIFIED');
    expect(v.projection.signature.officialTrust).toBe(false);expect(f.state.audits[0].subject).toEqual(receivedSubject(f.principal));
    expect(f.state.audits[0].subject.subjectId).toBeNull();expect(JSON.stringify(v)).not.toMatch(/grantKey|authRevision|storageKey|certificatePem|password/);
  });
  it('bounded keyset is explicitly live, sorted and scoped; not a history snapshot',async()=>{
    f.state.rows.push({...structuredClone(f.row),id:receivedId(20)});
    const a=await f.facade.list(f.token,'SERVICE',{...f.query,limit:1});expect(a.items).toHaveLength(1);expect(a.page.hasMore).toBe(true);
    expect(a.page.consistency).toBe('LIVE_KEYSET_NOT_SNAPSHOT');
    const b=await f.facade.list(f.token,'SERVICE',{...f.query,limit:1,after:a.page.nextAfter});expect(b.items[0].id).toBe(receivedId(20));expect(b.page.hasMore).toBe(false);
  });
  it.each(['xml','cdr','pdf'])('downloads exact %s provider original; no regenerated bytes',async kind=>{
    const artifact=f.state.originals[kind==='xml'?0:kind==='cdr'?1:2];
    const file=await f.facade.content(f.token,'SERVICE',f.scope,f.id,artifact.id);expect(file.bytes).toEqual(artifact.bytes);
    expect(file.sha256).toBe(artifact.sha256);expect(file.fileName).toBe(artifact.fileName);
  });
  it('an emission anchor or generic documents scope is not a reception grant',async()=>{
    f.state.grants.clear();await expect(f.facade.list(f.token,'SERVICE',f.query)).rejects.toMatchObject({status:403});
    f.principal.scopes=['b2b:documents:read','b2b:artifacts:read'];await expect(f.facade.list(f.token,'SERVICE',f.query)).rejects.toMatchObject({status:403});
  });
  it('READ alone does not grant ARTIFACT; a file permission does not grant base READ',async()=>{
    await f.grant('ARTIFACT',false,1);expect((await f.facade.detail(f.token,'SERVICE',f.scope,f.id)).document.id).toBe(f.id);
    await expect(f.facade.content(f.token,'SERVICE',f.scope,f.id,f.state.originals[0].id)).rejects.toMatchObject({status:403});
    await f.grant('READ',false,1);await expect(f.facade.detail(f.token,'SERVICE',f.scope,f.id)).rejects.toMatchObject({status:403});
  });
  it.each(['branch','ruc','company','unassigned'])('does not expose %s documents outside the granted recipient tuple',async field=>{
    if(field==='branch')f.row.branchId=receivedId(99);if(field==='ruc')f.row.recipientRuc='00000000202';if(field==='company')f.row.companyId=2;
    if(field==='unassigned')(f.row as any).branchId=null;
    await expect(f.facade.detail(f.token,'SERVICE',f.scope,f.id)).rejects.toMatchObject({status:404});
  });
  it('XML substitution or materialized projection mismatch blocks detail and download',async()=>{
    f.state.originals[0].bytes=Buffer.from('tampered');await expect(f.facade.detail(f.token,'SERVICE',f.scope,f.id)).rejects.toMatchObject({status:409});
    f.state.originals[0].bytes=f.xml;f.row.projection.items[0].quantity='999';
    await expect(f.facade.content(f.token,'SERVICE',f.scope,f.id,f.state.originals[0].id)).rejects.toMatchObject({status:409});
  });
  it('a hash-correct CDR for a different number is not accepted as related evidence',async()=>{
    const c=f.state.originals[1],before=c.sha256;c.bytes=Buffer.from(c.bytes.toString().replaceAll(f.p.fullNumber,f.p.series+'-99999999'));c.sha256=receivedHash(c.bytes);c.byteLength=c.bytes.length;expect(c.sha256).not.toBe(before);
    await expect(f.facade.content(f.token,'SERVICE',f.scope,f.id,c.id)).rejects.toThrow();
  });
  it('revocation denies previously read details and files',async()=>{
    await f.facade.detail(f.token,'SERVICE',f.scope,f.id);f.control.revoked=true;
    await expect(f.facade.content(f.token,'SERVICE',f.scope,f.id,f.state.originals[0].id)).rejects.toMatchObject({status:403});
  });
  it('audit failure releases no result and does not leak its internal text',async()=>{
    f.control.failAudit=true;await expect(f.facade.detail(f.token,'SERVICE',f.scope,f.id)).rejects.toThrow();expect(f.state.audits).toHaveLength(0);
  });
  it('no policy changes without a configured live step-up authority',async()=>{
    const closed=new B2bReceptionReads(f.store,f.identity);await expect(closed.setGrant('admin',{},0)).rejects.toMatchObject({status:503});
    f.admin.authorize.mockRejectedValueOnce(new Error('STEP_UP_DENIED'));await expect(f.grant('READ',false,1)).rejects.toThrow();
    expect((await f.facade.detail(f.token,'SERVICE',f.scope,f.id)).document.id).toBe(f.id);
  });
  it('step-up revocation after policy write rolls back the whole owner transaction',async()=>{
    f.admin.authorize.mockImplementation(async(_h,digest)=>({adminId:receivedId(90),authRevision:f.admin.authorize.mock.calls.length>=3?2:1,policySha256:digest}));
    // Reset call history only; existing committed policies remain intact.
    f.admin.authorize.mockClear();await expect(f.grant('READ',false,1)).rejects.toMatchObject({status:403});
    expect((await f.facade.detail(f.token,'SERVICE',f.scope,f.id)).document.id).toBe(f.id);
  });
  it.each([{limit:0},{limit:101},{from:'2025-01-01',to:'2026-02-01'},{after:'bad'},{type:'NV'}])('rejects invalid/oversized selection %j',async input=>{
    await expect(f.facade.list(f.token,'SERVICE',{...f.query,...input})).rejects.toMatchObject({status:400});
  });
});
